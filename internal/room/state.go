// Package room implements the deterministic playback state machine shared by
// all listeners of a room.
//
// Playback is described as a timeline rather than as a stream of events:
// "track T is at position P at server time A and is (not) playing". Any client
// can evaluate that description at any moment without further messages, which
// is what makes synchronisation robust against lost or late packets: the
// latest snapshot always wins, and while offline every phone keeps computing
// the same timeline, including automatic advances to the next track.
//
// The timeline rules implemented in timeline.go are mirrored in the web
// client (web/src/sync/timeline.ts). Both implementations are verified
// against the shared fixtures in testdata/sync.
package room

// Repeat is the repeat mode of a room.
type Repeat string

const (
	RepeatOff Repeat = "off"
	RepeatAll Repeat = "all"
	RepeatOne Repeat = "one"
)

// Valid reports whether r is a known repeat mode.
func (r Repeat) Valid() bool { return r == RepeatOff || r == RepeatAll || r == RepeatOne }

// Playback describes what is playing. While Playing, the position at server
// time t >= AnchorMs is PositionMs + (t - AnchorMs). Before AnchorMs the track
// is "armed": clients hold it at PositionMs and start exactly at AnchorMs.
type Playback struct {
	TrackID    string `json:"trackId"`
	EntryID    string `json:"entryId,omitempty"` // queue entry being played, if any
	PositionMs int64  `json:"positionMs"`
	AnchorMs   int64  `json:"anchorMs"`
	Playing    bool   `json:"playing"`
	DurationMs int64  `json:"durationMs"`
}

// QueueEntry is a track explicitly queued by a listener. Queued tracks play
// before the rest of the context.
type QueueEntry struct {
	ID      string `json:"id"`
	TrackID string `json:"trackId"`
	AddedBy string `json:"addedBy,omitempty"`
}

// Context is the collection playback walks through: a folder, playlist,
// the whole library or an ad-hoc list of tracks.
type Context struct {
	Kind   string   `json:"kind"`
	ID     string   `json:"id"`
	Name   string   `json:"name"`
	Tracks []string `json:"tracks"`
	// Order is the play order as indices into Tracks: the identity
	// permutation, or a shuffled one generated by the server.
	Order []int `json:"order"`
}

// Hold is set while a room waits for every listener to buffer a newly
// selected track ("wait for everyone").
type Hold struct {
	TrackID   string `json:"trackId"`
	EntryID   string `json:"entryId,omitempty"`
	StartedMs int64  `json:"startedMs"`
	UntilMs   int64  `json:"untilMs"`
}

// State is the complete, serialisable state of a room.
type State struct {
	Version  uint64   `json:"version"`
	Playback Playback `json:"playback"`
	// ContextIndex points into Context.Order at the last context track that
	// was played (-1 before the first one). It stays put while queued
	// entries play, so the context resumes where it left off.
	ContextIndex int    `json:"contextIndex"`
	Shuffle      bool   `json:"shuffle"`
	Repeat       Repeat `json:"repeat"`
	WaitForAll   bool   `json:"waitForAll"`
	Hold         *Hold  `json:"hold,omitempty"`

	QueueVersion uint64       `json:"queueVersion"`
	Queue        []QueueEntry `json:"queue"`

	ContextVersion uint64  `json:"contextVersion"`
	Context        Context `json:"context"`

	NextEntrySeq uint64 `json:"nextEntrySeq"`
}

// NewState returns the state of a fresh room.
func NewState() State {
	return State{
		ContextIndex: -1,
		Repeat:       RepeatOff,
		WaitForAll:   true,
		Queue:        []QueueEntry{},
		Context:      Context{Tracks: []string{}, Order: []int{}},
	}
}

// Clone returns a deep copy of s.
func (s State) Clone() State {
	c := s
	c.Queue = append([]QueueEntry(nil), s.Queue...)
	if c.Queue == nil {
		c.Queue = []QueueEntry{}
	}
	c.Context.Tracks = append([]string(nil), s.Context.Tracks...)
	c.Context.Order = append([]int(nil), s.Context.Order...)
	if c.Context.Tracks == nil {
		c.Context.Tracks = []string{}
	}
	if c.Context.Order == nil {
		c.Context.Order = []int{}
	}
	if s.Hold != nil {
		h := *s.Hold
		c.Hold = &h
	}
	return c
}

// Catalog resolves track durations. A track unknown to the catalog cannot
// be played and is skipped.
type Catalog interface {
	DurationMs(trackID string) (int64, bool)
}

// MapCatalog is a Catalog backed by a map, handy for tests.
type MapCatalog map[string]int64

// DurationMs implements Catalog.
func (m MapCatalog) DurationMs(id string) (int64, bool) {
	d, ok := m[id]
	return d, ok
}
